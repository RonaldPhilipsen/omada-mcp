#!/usr/bin/env python3
"""Generate internal/opsindex/ops_index.gen.go from the live Omada
northbound OpenAPI spec.

Generator rules (pinned):
  * Fetch the spec from
    https://use1-omada-northbound.tplinkcloud.com/v3/api-docs.
  * Assert sha256(spec) == the fingerprint pinned in gen/data/spec.sha256
    (copied from the sibling omada repo's gen/spec.sha256). On mismatch
    the generator fails: the index must always be built from the pinned
    spec.
  * For each (method, path) operation with a non-empty operationId, emit
    one Op. Tag and Summary come from the operation's tags[0] / summary
    fields (empty string when absent).
  * Mutability rule: mutating = true iff method != GET and the
    operationId does not start with "Get". The prefix match is
    case-insensitive because the spec's operationIds use a lowercase
    first letter (e.g. "getGridAllClients"); read-style search endpoints
    that POST but begin "Get" therefore classify non-mutating.
  * The emitted Ops slice is sorted by ID, so the same spec in always
    yields the same file out (deterministic; no timestamps in output).

The output file is gofmt-clean; `make verify` re-checks that and runs the
opsindex tests.
"""

import hashlib
import json
import os
import sys
import urllib.request

SPEC_URL = "https://use1-omada-northbound.tplinkcloud.com/v3/api-docs"
HTTP_METHODS = ("get", "post", "put", "delete", "patch", "head", "options")

HERE = os.path.dirname(os.path.abspath(__file__))
FINGERPRINT_FILE = os.path.join(HERE, "data", "spec.sha256")
OUTPUT_FILE = os.path.join(HERE, "..", "internal", "opsindex", "ops_index.gen.go")


def fetch_spec():
    """Fetch the raw spec bytes; fail on a non-200 response."""
    req = urllib.request.Request(SPEC_URL, headers={"User-Agent": "omada-mcp-gen/1.0"})
    with urllib.request.urlopen(req) as resp:
        if resp.status != 200:
            raise SystemExit(f"error: expected HTTP 200, got {resp.status}")
        return resp.read()


def pinned_fingerprint():
    """Return the SHA-256 hex digest pinned in gen/data/spec.sha256."""
    with open(FINGERPRINT_FILE) as f:
        return f.read().split()[0].lower()


def is_mutating(method, operation_id):
    """mutating = true iff method != GET and !operationId starts with "Get".

    The "Get" prefix match is case-insensitive: the spec's operationIds
    are lowercase-first, so a read-style POST such as getGridAllClients
    begins "Get" for rule purposes and classifies non-mutating.
    """
    return method != "GET" and not operation_id.lower().startswith("get")


def collect_ops(spec):
    """Return the index entries, sorted by ID, one per non-empty operationId."""
    ops = []
    seen = set()
    for path, methods in spec.get("paths", {}).items():
        for method, op in methods.items():
            if method.lower() not in HTTP_METHODS or not isinstance(op, dict):
                continue
            operation_id = op.get("operationId")
            if not operation_id:
                continue
            if operation_id in seen:
                raise SystemExit(f"error: duplicate operationId {operation_id!r}")
            seen.add(operation_id)
            tags = op.get("tags") or []
            ops.append(
                {
                    "id": operation_id,
                    "path": path,
                    "method": method.upper(),
                    "tag": tags[0] if tags else "",
                    "summary": op.get("summary") or "",
                    "mutating": is_mutating(method.upper(), operation_id),
                }
            )
    ops.sort(key=lambda op: op["id"])
    return ops


def go_str(value):
    """Render a Go string literal. JSON string escaping is a valid subset
    of Go string literal escaping (", \\, and \\uXXXX for controls)."""
    return json.dumps(value)


def render(ops, spec_sha):
    """Render the gofmt-clean Go source for the generated index."""
    lines = [
        "// Code generated by gen/genopsindex.py from the Omada northbound",
        "// OpenAPI spec; DO NOT EDIT.",
        f"// Source: {SPEC_URL}",
        f"// Spec SHA-256: {spec_sha}",
        "",
        "package opsindex",
        "",
        "// Op is one northbound API operation: its spec operationId, path",
        "// template, HTTP method, primary tag, and summary, plus the",
        "// pinned mutability classification (see gen/genopsindex.py).",
        "type Op struct {",
        "\tID, Path, Method, Tag, Summary string",
        "\tMutating                       bool",
        "}",
        "",
        "// Ops is the full operation index, sorted by ID.",
        "var Ops = []Op{",
    ]
    for op in ops:
        lines.append(
            "\t{ID: %s, Path: %s, Method: %s, Tag: %s, Summary: %s, Mutating: %s},"
            % (
                go_str(op["id"]),
                go_str(op["path"]),
                go_str(op["method"]),
                go_str(op["tag"]),
                go_str(op["summary"]),
                "true" if op["mutating"] else "false",
            )
        )
    lines += [
        "}",
        "",
        "// Lookup returns the Op with the given operation ID.",
        "func Lookup(id string) (Op, bool) {",
        "\tfor _, op := range Ops {",
        "\t\tif op.ID == id {",
        "\t\t\treturn op, true",
        "\t\t}",
        "\t}",
        "\treturn Op{}, false",
        "}",
        "",
    ]
    return "\n".join(lines)


def main():
    data = fetch_spec()
    spec_sha = hashlib.sha256(data).hexdigest()
    pinned = pinned_fingerprint()
    if spec_sha != pinned:
        raise SystemExit(
            "error: spec fingerprint mismatch:\n"
            f"  fetched: {spec_sha}\n"
            f"  pinned:  {pinned} (gen/data/spec.sha256)"
        )
    spec = json.loads(data)
    ops = collect_ops(spec)
    source = render(ops, spec_sha)
    with open(OUTPUT_FILE, "w") as f:
        f.write(source)
    mutating = sum(1 for op in ops if op["mutating"])
    print(
        f"wrote {os.path.normpath(OUTPUT_FILE)}: "
        f"{len(ops)} ops ({mutating} mutating, {len(ops) - mutating} non-mutating), "
        f"spec sha256 {spec_sha}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
